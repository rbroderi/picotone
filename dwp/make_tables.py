"""Collects every results/*.jsonl into one markdown file, results/tables.md."""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
cols = ["lstm_mac", "side_mac_saved_pct", "kbps", "snr_start", "snr_mid", "snr_end", "snr_dip", "lsd_bump", "codes", "codes_q8", "emb_snr", "snr_orig", "snr", "logmel", "mrstft", "d_snr", "d_logmel", "d_mrstft", "latent_snr", "latent_gain_db"]
head = {"snr_start": "SNR first 20 ms after seam", "snr_mid": "SNR mid-segment", "snr_end": "SNR last 20 ms", "snr_dip": "seam dip dB",
        "lsd_bump": "log-spectral bump at seam dB", "lstm_mac": "LSTM MAC ratio", "side_mac_saved_pct": "MAC saved (% of enc or dec)", "codes": "codes % (all cb)", "codes_q8": "codes % (first 8)",
        "emb_snr": "embedding SNR dB", "snr_orig": "SNR vs stock output dB", "snr": "SNR vs source dB", "logmel": "log-mel dB", "mrstft": "MR-STFT",
        "d_snr": "d SNR", "d_logmel": "d log-mel", "d_mrstft": "d MR-STFT", "latent_snr": "latent SNR dB", "latent_gain_db": "latent gain dB", "kbps": "kbps"}
out = ["# All measured rows", "",
       "Generated by `make_tables.py` from `results/*.jsonl`.  `d ...` columns are differences to the stock model at the same bitrate",
       "(positive d log-mel / d MR-STFT = worse, negative d SNR = worse).  Perceptual columns are measured against the source audio.", ""]
for path in sorted(glob.glob(os.path.join(HERE, "results", "*.jsonl"))):
    rows = [json.loads(l) for l in open(path)]
    rows = [r for r in rows if not r["label"].startswith(("MAC ", "A codebook"))]
    if not rows:
        continue
    use = [c for c in cols if any(c in r for r in rows)]
    out += [f"## {os.path.basename(path)}", "", "| variant | " + " | ".join(head[c] for c in use) + " |", "|---|" + "---|" * len(use)]
    for r in rows:
        vals = [(f"{r[c]:.2f}" if abs(r[c]) < 1e6 else "exact") if c in r and isinstance(r[c], (int, float)) else "" for c in use]
        out.append(f"| {r['label']} | " + " | ".join(vals) + " |")
    out.append("")
open(os.path.join(HERE, "results", "tables.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote results/tables.md,", len(out), "lines")
